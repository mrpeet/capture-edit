export const icon = (name) =>
  `<svg class="ico" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${P[name] ?? ''}</svg>`;

// Ersetzt den Inhalt eines Buttons: Icon, optional Text.
export function setBtn(el, name, text = '') {
  el.innerHTML = icon(name) + (text ? `<span>${text}</span>` : '');
}

// Setzt Icons vor den Inhalt aller Elemente mit data-icon (einmalig beim Start).
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]:not([data-hydrated])')) {
    el.insertAdjacentHTML('afterbegin', icon(el.dataset.icon));
    el.dataset.hydrated = '1';
  }
}
